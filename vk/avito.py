def load_manifest():
    sys.path.insert(0, ROOT)
    try:
        from catalog import store
    except ImportError:
        sys.path.insert(0, os.path.join(ROOT, "catalog"))
        import store  # type: ignore
    return {m["id"]: m for m in store.photos_manifest()}


def check_text(text, label):
    bad = (("цена", r"\d[\d\s]*(₽|руб)"), ("«у Димы»", r"\bДимы?\b"), ("поставщик", r"поставщик"),
           ("склад", r"\b(на|со)\s+склад"), ("остаток", r"\b\d+\s*(шт|комплект|компл|пар)\b"),
           ("оплата при получении", r"при получении"), ("постоплата", r"постоплат"),
           ("предоплата", r"\bпредоплат"), ("ссылка", r"https?://"), ("телефон", r"\+7[\s\(\)\d-]{9,}"))
    for name, rx in bad:
        m = re.search(rx, text, re.I)
        assert not m, f"{label}: в тексте запрещённое ({name}) → {m.group(0)!r}"
    assert len(text) <= 3200, f"{label}: текст {len(text)} знаков — для Авито это много"


def make_photos(src_files, dest_dir, limit=8):
    os.makedirs(dest_dir, exist_ok=True)
    saved = []
    for i, rel in enumerate(src_files[:limit], 1):
        p = os.path.join(ROOT, rel)
        if not os.path.exists(p):
            continue
        dst = os.path.join(dest_dir, f"{i}.jpg")
        im = Image.open(p).convert("RGB")
        if max(im.size) > 1200:
            im.thumbnail((1200, 1200), Image.LANCZOS)
        im.save(dst, quality=80, optimize=True)
        saved.append(dst)
    return saved


def build():
    man = load_manifest()
    idx = {r["id"]: r for r in json.load(open(
        os.path.join(ROOT, "catalog", "data", "catalog_index.json"), encoding="utf-8"))}
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(OUT, exist_ok=True)
    rows = []
    for it in PLAN:
        row = idx.get(it["id"], {})
        files = (man.get(it["id"]) or {}).get("files") or []
        assert files, f"{it['label']}: нет фото поставщика — объявление не собираем"
        name = str(it["label"]).replace("/", "-")
        folder = os.path.join(OUT, f"{it['n']:02d}_{name}")
        photos = make_photos(files, folder)
        text = it["desc"].strip()
        check_text(text, it["label"])
        check_text(it["avito_title"], it["label"] + " (заголовок)")
        body = f"""АВИТО · ОБЪЯВЛЕНИЕ

ЗАГОЛОВОК (вставьте в поле «Название»):
{it['avito_title']}

ОПИСАНИЕ (вставьте в поле «Описание»):
{text}

{CLOSER}

ЧТО ЗАПОЛНИТЬ В ФОРМЕ АВИТО:
· Категория: {it['avito_cat']}
· Состояние: Новое
· Цена: ваша (в форме, не в описании)
· Фото: загрузите по порядку 1.jpg → {len(photos)}.jpg
· Доставка: СДЭК по России
"""
        check_text(body, it["label"] + " (файл)")
        open(os.path.join(folder, "ОБЪЯВЛЕНИЕ.txt"), "w", encoding="utf-8").write(body)
        # отдельный файл под копипаст: только то, что идёт в поле «Описание»
        open(os.path.join(folder, "ОПИСАНИЕ_копировать.txt"), "w", encoding="utf-8").write(
            text + "\n\n" + CLOSER + "\n")
        rows.append({"n": it["n"], "label": it["label"], "folder": os.path.basename(folder),
                     "title": it["avito_title"], "photos": len(photos), "chars": len(text)})
        print(f"  {it['n']:>2}. {it['label'][:44]:46} фото {len(photos)} | {len(text)} знаков")

    # README и список
    readme = ["АВИТО · 20 ОБЪЯВЛЕНИЙ «В ОКОПЕ»", "",
              "Внутри — папки по номерам. В каждой:",
              "  · 1.jpg…N.jpg — фото товара, грузятся в объявление по порядку;",
              "  · ОБЪЯВЛЕНИЕ.txt — заголовок, описание и что заполнить в форме Авито;",
              "  · ОПИСАНИЕ_копировать.txt — только текст описания: открыть, выделить, скопировать, вставить.", "",
              "Цены в описаниях не указаны — ставите в поле «Цена» сами.",
              "Категория и остальные поля формы — в тексте объявления.", "",
              "СПИСОК:"]
    for r in rows:
        readme.append(f"  {r['n']:>2}. {r['label']} — {r['photos']} фото")
    check_text("\n".join(readme), "README")
    open(os.path.join(OUT, "README_КАК_ВЫКЛАДЫВАТЬ.txt"), "w", encoding="utf-8").write("\n".join(readme) + "\n")

    # архив
    os.makedirs(DIST, exist_ok=True)
    zip_path = os.path.join(DIST, "V_OKOPE_avito_20.zip")
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for root, _, files in os.walk(OUT):
            for f in sorted(files):
                p = os.path.join(root, f)
                z.write(p, os.path.join("V_OKOPE_Avito", os.path.relpath(p, OUT)))
    mb = os.path.getsize(zip_path) / 1e6
    print(f"\nархив: {zip_path} ({mb:.1f} МБ)")
    return rows


