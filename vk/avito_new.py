def check_text(text, label):
    bad = (("цена", r"\d[\d\s]*(₽|руб)"), ("«у Димы»", r"\bДимы?\b"), ("поставщик", r"поставщик"),
           ("склад", r"\b(на|со)\s+склад"), ("остаток", r"\b\d+\s*(шт|комплект|компл|пар)\b"),
           ("оплата при получении", r"при получении"), ("постоплата", r"постоплат"),
           ("предоплата", r"\bпредоплат"), ("ссылка", r"https?://"), ("телефон", r"\+7[\s\(\)\d-]{9,}"))
    for name, rx in bad:
        m = re.search(rx, text, re.I)
        assert not m, f"{label}: в тексте запрещённое ({name}) → {m.group(0)!r}"
    assert len(text) <= 3200, f"{label}: текст {len(text)} знаков — для Авито это много"


