def ts(s):
    return ("%02d:%02d:%06.3f" % (int(s // 3600), int((s % 3600) // 60), s % 60)).replace(".", ",")


cues, n = [], 1
for start, dur, parts in VO:
    tot = sum(len(p) for p in parts)
    t = start
    for p in parts:
        d = dur * len(p) / tot
        cues.append("%d\n%s --> %s\n%s\n" % (n, ts(t), ts(t + d), p))
        n += 1
        t += d
open(os.path.join(BASE, "ARKONA_REEL.srt"), "w", encoding="utf-8").write("\n".join(cues))
print("SRT:", len(cues), "реплик")

